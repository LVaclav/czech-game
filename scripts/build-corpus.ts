/**
 * Helper to generate standard PastForms from a masculine singular l-participle stem
 * e.g. pastStem = "dělal" -> dělal, dělala, dělalo, dělali
 * Automatically handles 2nd-position clitic word order for reflexive "se" / "si":
 *   ja_m: "učil jsem se", ty_m: "učil jsi se" / "učils se"? In Czech, "učil ses" (for se) or "učil jsi se", "učil sis" (for si) or "učil jsi si"
 */
function makePast(
  lMasc: string,
  reflexive: 'se' | 'si' | null = null,
  overrides?: Partial<{
    lFem: string;
    lNeut: string;
    lPlur: string;
  }>
): PastForms {
  const lFem = overrides?.lFem || `${lMasc}a`;
  const lNeut = overrides?.lNeut || `${lMasc}o`;
  const lPlur = overrides?.lPlur || `${lMasc}i`;

  if (!reflexive) {
    return {
      ja_m: [`${lMasc} jsem`],
      ja_f: [`${lFem} jsem`],
      ty_m: [`${lMasc} jsi`],
      ty_f: [`${lFem} jsi`],
      on: [lMasc],
      ona: [lFem],
      ono: [lNeut],
      my: [`${lPlur} jsme`],
      vy: [`${lPlur} jste`],
      oni: [lPlur],
    };
  }

  const contractedTy = reflexive === 'se' ? 'ses' : 'sis';

  return {
    ja_m: [`${lMasc} jsem ${reflexive}`],
    ja_f: [`${lFem} jsem ${reflexive}`],
    ty_m: [`${lMasc} jsi ${reflexive}`, `${lMasc} ${contractedTy}`],
    ty_f: [`${lFem} jsi ${reflexive}`, `${lFem} ${contractedTy}`],
    on: [`${lMasc} ${reflexive}`],
    ona: [`${lFem} ${reflexive}`],
    ono: [`${lNeut} ${reflexive}`],
    my: [`${lPlur} jsme ${reflexive}`],
    vy: [`${lPlur} jste ${reflexive}`],
    oni: [`${lPlur} ${reflexive}`],
  };
}

/**
 * Helper to generate Imperfective Future forms ("budu + infinitive")
 * with strict 2nd-position clitic placement for reflexive verbs ("budu se učit").
 */
function makeFutureImpf(
  fullInfinitive: string,
  reflexive: 'se' | 'si' | null = null
): PresentOrFutureForms {
  if (!reflexive) {
    return {
      ja: [`budu ${fullInfinitive}`],
      ty: [`budeš ${fullInfinitive}`],
      thirdSg: [`bude ${fullInfinitive}`],
      my: [`budeme ${fullInfinitive}`],
      vy: [`budete ${fullInfinitive}`],
      oni: [`budou ${fullInfinitive}`],
    };
  }

  const baseInf = fullInfinitive.replace(/\s+(se|si)$/, '').trim();
  return {
    ja: [`budu ${reflexive} ${baseInf}`],
    ty: [`budeš ${reflexive} ${baseInf}`],
    thirdSg: [`bude ${reflexive} ${baseInf}`],
    my: [`budeme ${reflexive} ${baseInf}`],
    vy: [`budete ${reflexive} ${baseInf}`],
    oni: [`budou ${reflexive} ${baseInf}`],
  };
}

/**
 * Helper for regular -at (5. třída: dělám, děláš, dělá, děláme, děláte, dělají)
 */
function makePresentAt(
  stem: string,
  reflexive: 'se' | 'si' | null = null
): PresentOrFutureForms {
  const s = reflexive ? ` ${reflexive}` : '';
  return {
    ja: [`${stem}ám${s}`],
    ty: [`${stem}áš${s}`],
    thirdSg: [`${stem}á${s}`],
    my: [`${stem}áme${s}`],
    vy: [`${stem}áte${s}`],
    oni: [`${stem}ají${s}`],
  };
}

/**
 * Helper for regular -it/-et/-ět (4. třída: mluvím, mluvíš, mluví, mluvíme, mluvíte, mluví / rozumějí)
 */
function makePresentIt(
  stem: string,
  reflexive: 'se' | 'si' | null = null,
  oniAlt?: string
): PresentOrFutureForms {
  const s = reflexive ? ` ${reflexive}` : '';
  const oniForms = oniAlt ? [`${stem}í${s}`, `${oniAlt}${s}`] : [`${stem}í${s}`];
  return {
    ja: [`${stem}ím${s}`],
    ty: [`${stem}íš${s}`],
    thirdSg: [`${stem}í${s}`],
    my: [`${stem}íme${s}`],
    vy: [`${stem}íte${s}`],
    oni: oniForms,
  };
}

/**
 * Helper for regular -ovat (3. třída: pracuju/pracuji, pracuješ, pracuje, pracujeme, pracujete, pracujou/pracují)
 */
function makePresentOvat(
  stem: string, // stem before -ovat, e.g. "prac" for "pracovat"
  reflexive: 'se' | 'si' | null = null
): PresentOrFutureForms {
  const s = reflexive ? ` ${reflexive}` : '';
  return {
    ja: [`${stem}uju${s}`, `${stem}uji${s}`],
    ty: [`${stem}uješ${s}`],
    thirdSg: [`${stem}uje${s}`],
    my: [`${stem}ujeme${s}`],
    vy: [`${stem}ujete${s}`],
    oni: [`${stem}ujou${s}`, `${stem}ují${s}`],
  };
}

